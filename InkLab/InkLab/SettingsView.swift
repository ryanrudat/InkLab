import SwiftUI
import InkLabRecognition

struct SettingsView: View {
    @EnvironmentObject private var settings: AppSettings
    @Environment(\.dismiss) private var dismiss

    var body: some View {
        NavigationStack {
            Form {
                Section("Paper") {
                    Picker("Default paper", selection: $settings.defaultPaper) {
                        ForEach(PaperType.allCases) { Text($0.label).tag($0) }
                    }
                }
                Section {
                    Toggle("Left-handed", isOn: $settings.leftHanded)
                    Toggle("Finger / mouse drawing", isOn: $settings.fingerDrawing)
                    Toggle("Auto-run “@” commands", isOn: $settings.autoCommands)
                    Toggle("Snap shapes on hold", isOn: $settings.snapShapesOnHold)
                } header: {
                    Text("Writing")
                } footer: {
                    Text("Finger/mouse drawing: keep on to draw in the Simulator (no Apple Pencil). Auto-run “@” commands: when you handwrite something starting with “@” and pause, it runs automatically — turn off for distraction-free notes. Snap shapes on hold: draw a line or shape and hold the pencil still for ~½ second to snap it into a clean form.")
                }
                Section {
                    Toggle("Allow AI generation", isOn: $settings.cloudAIConsentGranted)
                    if settings.cloudAIConsentGranted {
                        Picker("Account", selection: Binding(
                            get: { settings.userKind.wire },
                            set: { settings.userKind = UserKind(wire: $0) }
                        )) {
                            ForEach([UserKind.adult, .minorConsented, .minorUnconsented, .schoolManaged], id: \.wire) { kind in
                                Text(kind.settingsLabel).tag(kind.wire)
                            }
                        }
                        if settings.userKind != .adult {
                            Toggle("Age verified", isOn: $settings.ageVerified)
                        }
                    }
                } header: {
                    Text("Cloud AI")
                } footer: {
                    Text("Turn this on to opt in to cloud AI (App Store §5.1.2(i)), through your InkLab Server. “@” widgets like “@a calculator” are generated by OpenAI’s GPT from your prompt text, not your ink. When you ask InkLab to read handwriting, an image of just that writing is sent to Anthropic’s Claude. Minors need verifiable parental consent (COPPA/FERPA).")
                }
                Section {
                    // Accurate either way: with cloud AI on, handwriting you ask InkLab to read goes to Claude.
                    LabeledContent("Recognition", value: settings.cloudAIConsentGranted
                                   ? "Apple Vision on-device, Claude when you ask" : "Apple Vision (on-device)")
                    LabeledContent("Privacy", value: settings.cloudAIConsentGranted
                                   ? "Ink stays on device unless you send it to be read" : "On-device only; no ink leaves the device")
                } header: { Text("About") }
            }
            .scrollContentBackground(.hidden)
            .background(Color.inkPaper)
            .tint(Color.inkSun)                  // toggles in sun orange, not system green
            .navigationTitle("Settings")
            .toolbar { ToolbarItem(placement: .confirmationAction) { Button("Done") { dismiss() } } }
        }
    }
}
